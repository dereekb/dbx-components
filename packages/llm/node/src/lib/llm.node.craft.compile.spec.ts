import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, utimesSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { makeLlmCraftSiteRegistry, type LlmCraftNote } from '@dereekb/llm/craft';
import { compileLlmCraftNotes, renderLlmCraftNotesModule, writeLlmCraftNotesModule } from './llm.node.craft.compile';

const SITES = makeLlmCraftSiteRegistry({
  sites: {
    'product-page': { facts: { category: 'closed', brand: 'open', bundle: 'boolean' }, inputs: ['brief', 'notes'] },
    'release-notes': { facts: { audience: 'closed' }, inputs: ['summary'] }
  }
});

const NOTE: LlmCraftNote = { id: 'apparel-plain', title: 'Plain apparel pages', sites: ['product-page'], where: {}, floor: 0.6, unserved: 'omit', priority: 4, enabled: true, body: 'Name the fabric first.', tier: 'builtin', source: 'apparel-plain.md' };

function noteText(id: string, body = 'Name the fabric first.'): string {
  return `---\nid: ${id}\ntitle: ${id}\nsites: [product-page]\n---\n${body}\n`;
}

/**
 * The JSON literal of a rendered module's export.
 *
 * @param text - The module text.
 * @returns The parsed notes.
 */
function exportedNotesOf(text: string): unknown {
  const start = text.indexOf('= ') + 2;
  return JSON.parse(text.slice(start, text.lastIndexOf(';')));
}

let dir: string;

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'llm-node-craft-'));
});

afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

describe('renderLlmCraftNotesModule()', () => {
  it('renders the default module', () => {
    expect(renderLlmCraftNotesModule({ notes: [NOTE], exportName: 'BUILTIN_CRAFT_NOTES' })).toBe(
      [
        '/**',
        ' * GENERATED — do not edit. Craft notes compiled from a folder of markdown files; re-emit this module instead of editing it.',
        ' */',
        '',
        "import type { LlmCraftNote } from '@dereekb/llm/craft';",
        '',
        '/**',
        ' * The compiled craft notes.',
        ' */',
        `export const BUILTIN_CRAFT_NOTES: ReadonlyArray<LlmCraftNote> = ${JSON.stringify([NOTE], null, 2)};`,
        ''
      ].join('\n')
    );
  });

  it('renders a custom type, import, header and export doc', () => {
    const text = renderLlmCraftNotesModule({ notes: [], exportName: 'SHOP_NOTES', typeName: 'ShopNote', typeFrom: './shop-note', header: ['GENERATED by the shop compiler.', 'Edit the markdown, then re-emit.'], exportDoc: 'The shop tier.' });
    expect(text).toBe(['/**', ' * GENERATED by the shop compiler.', ' * Edit the markdown, then re-emit.', ' */', '', "import type { ShopNote } from './shop-note';", '', '/**', ' * The shop tier.', ' */', 'export const SHOP_NOTES: ReadonlyArray<ShopNote> = [];', ''].join('\n'));
  });
});

describe('compileLlmCraftNotes()', () => {
  it('compiles a folder: README skipped, notes sorted by id, a refused file reported, the text the render', () => {
    writeFileSync(join(dir, 'z.md'), noteText('alpha-note'));
    writeFileSync(join(dir, 'a.md'), noteText('zeta-note'));
    writeFileSync(join(dir, 'README.md'), 'people only');
    writeFileSync(join(dir, 'broken.md'), 'no fence');
    const compiled = compileLlmCraftNotes({ dir, tier: 'builtin', sites: SITES, exportName: 'BUILTIN_CRAFT_NOTES' });

    expect(compiled.tier).toBe('builtin');
    expect(compiled.notes.map((note) => note.id)).toEqual(['alpha-note', 'zeta-note']);
    expect(compiled.refused.map((refusal) => refusal.source)).toEqual(['broken.md']);
    expect(compiled.text).toBe(renderLlmCraftNotesModule({ notes: compiled.notes, exportName: 'BUILTIN_CRAFT_NOTES' }));
    expect(exportedNotesOf(compiled.text)).toEqual(compiled.notes);
  });

  it('throws on a folder that does not exist', () => {
    expect(() => compileLlmCraftNotes({ dir: join(dir, 'missing'), tier: 'builtin', sites: SITES, exportName: 'X' })).toThrow(/is not a folder/);
  });
});

describe('writeLlmCraftNotesModule()', () => {
  it('writes the module atomically, creating the parent folder', () => {
    writeFileSync(join(dir, 'a.md'), noteText('alpha-note'));
    const outDir = join(dir, 'out', 'nested');
    const out = join(outDir, 'craft-notes.generated.ts');
    const compiled = writeLlmCraftNotesModule({ dir, tier: 'builtin', sites: SITES, exportName: 'BUILTIN_CRAFT_NOTES', out });

    expect(compiled.outcome).toBe('wrote');
    expect(readFileSync(out, 'utf8')).toBe(compiled.text);
    expect(readdirSync(outDir).filter((name) => name.endsWith('.writing'))).toEqual([]);
  });

  it('leaves an unchanged module untouched: the second write reports unchanged and the mtime does not move', () => {
    writeFileSync(join(dir, 'a.md'), noteText('alpha-note'));
    const out = join(dir, 'craft-notes.generated.ts');
    const config = { dir, tier: 'builtin', sites: SITES, exportName: 'BUILTIN_CRAFT_NOTES', out };
    const first = writeLlmCraftNotesModule(config);
    const past = new Date('2020-01-01T00:00:00Z');
    utimesSync(out, past, past);
    const before = statSync(out).mtimeMs;
    const second = writeLlmCraftNotesModule(config);

    expect(first.outcome).toBe('wrote');
    expect(second.outcome).toBe('unchanged');
    expect(second.text).toBe(first.text);
    expect(statSync(out).mtimeMs).toBe(before);

    writeFileSync(join(dir, 'b.md'), noteText('beta-note'));
    expect(writeLlmCraftNotesModule(config).outcome).toBe('wrote');
    expect(statSync(out).mtimeMs).not.toBe(before);
  });

  it('refuses on any refusal, listing the line, and leaves an existing module untouched', () => {
    writeFileSync(join(dir, 'a.md'), noteText('alpha-note'));
    writeFileSync(join(dir, 'broken.md'), 'no fence');
    const out = join(dir, 'craft-notes.generated.ts');
    writeFileSync(out, 'PREVIOUS');

    expect(() => writeLlmCraftNotesModule({ dir, tier: 'builtin', sites: SITES, exportName: 'BUILTIN_CRAFT_NOTES', out })).toThrow(`${join(dir, 'broken.md')}: line 1: a craft note opens with a \`---\` frontmatter fence`);
    expect(readFileSync(out, 'utf8')).toBe('PREVIOUS');
    expect(existsSync(`${out}.${process.pid}.writing`)).toBe(false);
  });
});
